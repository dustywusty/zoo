// Package keeper manages squid: the only way out of a cage.
//
// The keeper runs in its own VM or container attached to two networks: the
// internal cage network (no route out) and one with a route out. Cages
// can reach nothing but the keeper; the keeper enforces a default-deny
// allowlist and logs every request to ~/.zoo/keeper/log/access.log.
package keeper

